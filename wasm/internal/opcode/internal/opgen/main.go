// Command opgen writes the opcode package's tables -- every opcode's
// constant, its text name and the signatures of the operators that have one --
// from the opcode lists of a V8 checkout's src/wasm/wasm-opcodes.h, which
// group the opcodes by how they are decoded.
//
// Usage:
//
//	go run ./wasm/internal/opcode/internal/opgen /path/to/v8/src/wasm/wasm-opcodes.h > /tmp/tables.go &&
//	  mv /tmp/tables.go wasm/internal/opcode/tables.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type entry struct {
	name   string
	code   uint32
	sig    string
	text   string
	sig64  string
	source string
}

var (
	defineRE = regexp.MustCompile(`(?m)^#define (FOREACH_\w+)\(V\)`)
	entryRE  = regexp.MustCompile(`V\(\s*(\w+),\s*(0x[0-9a-fA-F]+),\s*(\w+),\s*"([^"]*)"(?:,\s*(\w+))?\s*\)`)
	sigRE    = regexp.MustCompile(`V\(\s*(\w+),\s*(kWasm\w+(?:,\s*kWasm\w+)*)\s*\)`)
	useRE    = regexp.MustCompile(`(FOREACH_\w+)\(V\)`)
	commRE   = regexp.MustCompile(`/\*.*?\*/`)
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: opgen path/to/wasm-opcodes.h")
		os.Exit(2)
	}
	src, err := os.ReadFile(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	text := strings.ReplaceAll(string(src), "\r\n", "\n")
	bodies := map[string]string{}
	for _, loc := range defineRE.FindAllStringSubmatchIndex(text, -1) {
		name := text[loc[2]:loc[3]]
		rest := text[loc[1]:]
		var body strings.Builder
		for _, line := range strings.Split(rest, "\n") {
			body.WriteString(commRE.ReplaceAllString(line, ""))
			body.WriteByte(' ')
			if !strings.HasSuffix(strings.TrimSpace(line), "\\") {
				break
			}
		}
		bodies[name] = strings.ReplaceAll(body.String(), "\\", " ")
	}
	var expand func(list string) []entry
	expand = func(list string) []entry {
		body, ok := bodies[list]
		if !ok {
			fmt.Fprintln(os.Stderr, "no list", list)
			os.Exit(1)
		}
		var out []entry
		// Entries and nested lists, in order.
		type item struct {
			at int
			e  *entry
			l  string
		}
		var items []item
		for _, m := range entryRE.FindAllStringSubmatchIndex(body, -1) {
			code, _ := strconv.ParseUint(body[m[4]:m[5]], 0, 32)
			e := &entry{name: body[m[2]:m[3]], code: uint32(code), sig: body[m[6]:m[7]], text: body[m[8]:m[9]], source: list}
			if m[10] >= 0 {
				e.sig64 = body[m[10]:m[11]]
			}
			items = append(items, item{at: m[0], e: e})
		}
		for _, m := range useRE.FindAllStringSubmatchIndex(body, -1) {
			items = append(items, item{at: m[0], l: body[m[2]:m[3]]})
		}
		sort.Slice(items, func(i, j int) bool { return items[i].at < items[j].at })
		for _, it := range items {
			if it.e != nil {
				out = append(out, *it.e)
			} else {
				out = append(out, expand(it.l)...)
			}
		}
		return out
	}

	all := expand("FOREACH_OPCODE")
	seen := map[uint32]string{}
	for _, e := range all {
		if prev, ok := seen[e.code]; ok {
			fmt.Fprintf(os.Stderr, "duplicate opcode 0x%x: %s and %s\n", e.code, prev, e.name)
			os.Exit(1)
		}
		seen[e.code] = e.name
	}

	// Signatures, in the list's order.
	var sigNames []string
	sigTypes := map[string][]string{}
	sigBody := bodies["FOREACH_SIGNATURE"] + " " + bodies["FOREACH_SIMD_SIGNATURE"]
	for _, m := range sigRE.FindAllStringSubmatch(sigBody, -1) {
		if _, ok := sigTypes[m[1]]; ok {
			continue
		}
		sigNames = append(sigNames, m[1])
		var ts []string
		for _, t := range strings.Split(m[2], ",") {
			ts = append(ts, strings.TrimSpace(t))
		}
		sigTypes[m[1]] = ts
	}
	sort.Strings(sigNames)

	var b bytes.Buffer
	b.WriteString("// Code generated by opgen from wasm-opcodes.h; DO NOT EDIT.\n\n")
	b.WriteString("package opcode\n\nimport \"github.com/go-quickjs/go-quickjs/wasm/internal/module\"\n\n")
	b.WriteString("// The opcodes, each in its list's order.\nconst (\n")
	for _, e := range all {
		fmt.Fprintf(&b, "\t%s Opcode = 0x%x // %s\n", e.name, e.code, e.text)
	}
	b.WriteString(")\n\n")

	// Name tables, by encoding range.
	type table struct {
		name string
		lo   uint32
	}
	tables := []table{
		{"names00", 0x00}, {"namesFA", 0xfa00}, {"namesFB", 0xfb00}, {"namesFC", 0xfc00},
		{"namesFD", 0xfd00}, {"namesFD1", 0xfd100}, {"namesFE", 0xfe00},
	}
	for _, t := range tables {
		fmt.Fprintf(&b, "var %s = [256]string{\n", t.name)
		for _, e := range all {
			if e.code >= t.lo && e.code < t.lo+256 {
				fmt.Fprintf(&b, "\t0x%02x: %q,\n", e.code-t.lo, e.text)
			}
		}
		b.WriteString("}\n\n")
	}

	// Signatures.
	goType := map[string]string{
		"kWasmI32": "module.ValueType{Kind: module.KindI32}", "kWasmI64": "module.ValueType{Kind: module.KindI64}",
		"kWasmF32": "module.ValueType{Kind: module.KindF32}", "kWasmF64": "module.ValueType{Kind: module.KindF64}",
		"kWasmS128":    "module.ValueType{Kind: module.KindV128}",
		"kWasmAnyRef":  "module.ValueType{Kind: module.KindRef, Nullable: true, Heap: module.HeapAny}",
		"kWasmFuncRef": "module.ValueType{Kind: module.KindRef, Nullable: true, Heap: module.HeapFunc}",
		"kWasmEqRef":   "module.ValueType{Kind: module.KindRef, Nullable: true, Heap: module.HeapEq}",
	}
	b.WriteString("// The signatures, by name: the result's code, an underscore, the parameters'\n// codes (i i32, l i64, f f32, d f64, s v128, v none).\nconst (\n\tsigNone sigIndex = iota\n")
	for _, n := range sigNames {
		fmt.Fprintf(&b, "\tsig_%s\n", n)
	}
	b.WriteString(")\n\nvar sigs = [...]Sig{\n\tsigNone: {},\n")
	for _, n := range sigNames {
		ts := sigTypes[n]
		var res, par []string
		if ts[0] != "kWasmVoid" {
			res = append(res, goType[ts[0]])
		}
		for _, t := range ts[1:] {
			g, ok := goType[t]
			if !ok {
				fmt.Fprintln(os.Stderr, "unknown type", t)
				os.Exit(1)
			}
			par = append(par, g)
		}
		fmt.Fprintf(&b, "\tsig_%s: {", n)
		if len(par) > 0 {
			fmt.Fprintf(&b, "Params: []module.ValueType{%s}, ", strings.Join(par, ", "))
		}
		if len(res) > 0 {
			fmt.Fprintf(&b, "Results: []module.ValueType{%s}", strings.Join(res, ", "))
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")

	sigTable := func(name string, lists []string, use64 bool, low byte) {
		fmt.Fprintf(&b, "var %s = [256]sigIndex{\n", name)
		set := map[uint32]bool{}
		for _, l := range lists {
			for _, e := range expand(l) {
				s := e.sig
				if use64 {
					s = e.sig64
				}
				if s == "_" || s == "" {
					continue
				}
				idx := e.code & 0xff
				if set[idx] {
					continue
				}
				set[idx] = true
				fmt.Fprintf(&b, "\t0x%02x: sig_%s, // %s\n", idx, s, e.text)
			}
		}
		b.WriteString("}\n\n")
	}
	sigTable("sigs00", []string{"FOREACH_SIMPLE_OPCODE", "FOREACH_SIMPLE_PROTOTYPE_OPCODE", "FOREACH_SIGN_EXTENSION_OPCODE"}, false, 0)
	sigTable("sigsFA", []string{"FOREACH_ASMJS_COMPAT_OPCODE"}, false, 0)
	sigTable("sigsFC", []string{"FOREACH_NUMERIC_OPCODE_WITH_SIG"}, false, 0)
	sigTable("sigsFD", []string{"FOREACH_SIMD_MVP_0_OPERAND_OPCODE", "FOREACH_SIMD_MEM_OPCODE", "FOREACH_SIMD_MEM_1_OPERAND_OPCODE"}, false, 0)
	sigTable("sigsFD1", []string{"FOREACH_RELAXED_SIMD_OPCODE"}, false, 0)
	sigTable("sigsAtomic32", []string{"FOREACH_ATOMIC_OPCODE", "FOREACH_ATOMIC_0_OPERAND_OPCODE"}, false, 0)
	sigTable("sigsAtomic64", []string{"FOREACH_ATOMIC_OPCODE", "FOREACH_ATOMIC_0_OPERAND_OPCODE"}, true, 0)

	out, err := format.Source(b.Bytes())
	if err != nil {
		os.Stdout.Write(b.Bytes())
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	os.Stdout.Write(out)
}
