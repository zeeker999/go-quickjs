// seeds returns the valid modules the mutations start from.
func seeds() []corpusCase {
	return []corpusCase{
		{"seed/numeric", numericSeed()},
		{"seed/memory", memorySeed()},
		{"seed/control", controlSeed()},
		{"seed/gc", gcSeed()},
		{"seed/legacy-eh", legacyEHSeed()},
		{"seed/exnref", exnrefSeed()},
		{"seed/const", constSeed()},
	}
}
