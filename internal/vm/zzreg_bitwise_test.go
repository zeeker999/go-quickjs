// TestRegBitwiseToInt32 pins the bitwise operators' ToInt32 and ToUint32
// in both modes, fast path and slow: fractions, numbers past 2^31 and
// 2^32, -0, numbers near 2^63 and beyond, NaN, the infinities, the
// smallest denormal, a string, and a BigInt's TypeError.
func TestRegBitwiseToInt32(t *testing.T) {
	const src = `
		function or0(x) { return x | 0 }
		function ops(x, y) { return [x & y, x | y, x ^ y, x << y, x >> y, x >>> y, x & 255, x >>> 0, x << 3, x >> 1].join(",") }
		var xs = [3.7, -3.7, 0.5, -0, 2147483648, 4294967301, -2147483649, 1e18, -1e18, 9223372036854774784,
			9223372036854775808, -9223372036854775808, 1e300, NaN, Infinity, -Infinity, 5e-324, "12", 4503599627370497.5];
		var out = [xs.map(or0).join(",")];
		for (var i = 0; i < xs.length; i++) out.push(ops(xs[i], xs[(i + 3) % xs.length]));
		try { or0(1n) } catch (e) { out.push(e instanceof TypeError) }
		out.join(" ")`
	regRunBoth(t, src, regBitwiseWant, 3)
}

