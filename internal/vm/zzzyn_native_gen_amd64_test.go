// The native handlers' emitter (zzzyn_native_amd64.go): the handlers made
// by the JIT's assembler, offline, and written as the assembled block
// zzzyn_native_handlers_amd64.s by TestRegNativeGenerated with -nativegen
// (go generate ./internal/vm). The emitter is a test's so that the
// package's code needs no assembler: what the binary holds is the block.

//go:generate go test -run ^TestRegNativeGenerated$ -nativegen .

var nativeGenWrite = flag.Bool("nativegen", false, "write the native handlers' assembled block (zzzyn_native_handlers_amd64.s)")

// nativeHandlersFile is the assembled block's file.
const nativeHandlersFile = "zzzyn_native_handlers_amd64.s"

// nativeSource is the assembled block's source for the code b, its
// handlers at offs: the code as bytes in one TEXT symbol and the table a
// symbol of the handlers' addresses, every operation's that has none the
// exit stub's, which the linker resolves.
func nativeSource(b []byte, offs nativeOffsets) string {
	var s strings.Builder
	s.WriteString("// Code generated by TestRegNativeGenerated (zzzyn_native_gen_amd64_test.go). DO NOT EDIT.\n\n#include \"textflag.h\"\n\n")
	fmt.Fprintf(&s, "// regNativeHandlers is the register interpreter's native handlers, %d\n", len(b))
	s.WriteString("// bytes of position-independent machine code made by nativeEmit: every\n// address it needs is in the context it is given in DI. Its handlers, in\n// order:\n//\n")
	for _, op := range offs.order {
		fmt.Fprintf(&s, "//\t%5d  %s\n", offs.at[op], op)
	}
	s.WriteString("TEXT ·regNativeHandlers(SB), NOSPLIT|NOFRAME, $0-0\n")
	for i := 0; i < len(b); i += 16 {
		var parts []string
		for _, c := range b[i:min(i+16, len(b))] {
			parts = append(parts, fmt.Sprintf("BYTE $0x%02x", c))
		}
		s.WriteString("\t" + strings.Join(parts, "; ") + "\n")
	}
	s.WriteString("\n// regNativeTable is the native table: each operation's handler's address,\n// the exit stub's where it has none.\n")
	for op := 0; op < 256; op++ {
		at := offs.exit
		if o, ok := offs.at[bytecode.ROp(op)]; ok {
			at = o
		}
		fmt.Fprintf(&s, "DATA ·regNativeTable+%d(SB)/8, $·regNativeHandlers+%d(SB)\n", 8*op, at)
	}
	s.WriteString("GLOBL ·regNativeTable(SB), RODATA, $2048\n")
	return s.String()
}

// TestRegNativeGenerated checks that the assembled block is the code
// nativeEmit makes now, and writes it with -nativegen. One block serves
// every build: what the code reads of a layout that a tag changes, it
// reads relative to a base the context gives (rtBase, ccBase), so that
// the block made under any tag is the one file; the test fails under a
// tag whose layouts would make it another. A change to the emitter or to
// the layouts its offsets come from fails it until the block is written
// again (go generate ./internal/vm).
func TestRegNativeGenerated(t *testing.T) {
	b, offs := nativeEmit()
	src := nativeSource(b, offs)
	if *nativeGenWrite {
		if err := os.WriteFile(nativeHandlersFile, []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %d bytes of handlers", len(b))
		return
	}
	old, err := os.ReadFile(nativeHandlersFile)
	if err != nil {
		t.Fatal(err)
	}
	if string(bytes.ReplaceAll(old, []byte("\r\n"), []byte("\n"))) != src {
		t.Fatalf("%s is not the code nativeEmit makes: go generate ./internal/vm", nativeHandlersFile)
	}
	// The block the binary holds is the file's.
	base := nativeHandlersAddr()
	if got := unsafe.Slice((*byte)(nativePtr(&base)), len(b)); !bytes.Equal(got, b) {
		t.Fatal("the linked block differs from the emitter's code")
	}
	at := nativeTableAddr()
	tab := (*[256]uintptr)(nativePtr(&at))
	for op := 0; op < 256; op++ {
		want := offs.exit
		if o, ok := offs.at[bytecode.ROp(op)]; ok {
			want = o
		}
		if tab[op] != base+uintptr(want) {
			t.Fatalf("table entry %d is %#x, want %#x", op, tab[op], base+uintptr(want))
		}
	}
}

