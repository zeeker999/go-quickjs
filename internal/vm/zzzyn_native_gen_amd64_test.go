	for n, l := range g.exits {
		if n == 0 {
			continue
		}
		a.Bind(l)
		a.StoreImm(RDI, scr(15), int32(n))
		a.Jmp(g.exit)
	}
	b, err := a.Finish()
	if err != nil {
		panic(err)
	}
	offs := nativeOffsets{exit: a.Offset(g.exit), at: map[bytecode.ROp]int{}, order: order}
	for _, op := range order {
		offs.at[op] = a.Offset(labels[op])
	}
	return b, offs
