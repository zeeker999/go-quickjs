package nativegen

import (
	. "github.com/go-quickjs/go-quickjs/internal/jit/asm/amd64"
)

// switchW is switch: the body of R[A]'s case in the table switches[BC],
// as regSwitchTable.lookup finds it, for a number of a dense table and a
// flat string, by its cases' constants and then their texts, up to
// nativeFlatEqMax bytes; past the instruction where its table has no case
// for it; a boolean's or null's case, and none for anything else. The
// rest is Go's: a number of a table of few or scattered cases, a rope, a
// longer text.
func (g *nativeGen) switchW() {
	a := g.a
	str, to, none, loop, next := a.NewLabel(), a.NewLabel(), a.NewLabel(), a.NewLabel(), a.NewLabel()
	text, words, bytes, found := a.NewLabel(), a.NewLabel(), a.NewLabel(), a.NewLabel()
	isStr, null, other := a.NewLabel(), a.NewLabel(), a.NewLabel()
	// t := switches[BC].
	a.MovRR(RCX, RAX)
	a.ShiftImm(Shr, RCX, 32, true)
	a.Load(R8, RDI, ncRC)
	a.CmpMem(RCX, R8, offRCSwitches+8, true)
	a.Jcc(CondAE, g.exit)
	a.Load(R8, R8, offRCSwitches)
	a.LoadIdx(R8, R8, RCX, 8, 0)
	g.decA(RDX)
	a.LoadIdx(R9, R12, RDX, 1, 0)
	a.Op(Cmp, R9, R10, true)
	a.Jcc(CondAE, str)
	// A number: dense[f-lo] where lo <= f <= hi and f-lo an integer; no
	// case where the table has no number's.
	numbers := a.NewLabel()
	a.Load(RSI, R8, offSwDense)
	a.Op(Test, RSI, RSI, true)
	a.Jcc(CondNE, numbers)
	a.CmpMemImm8(R8, offSwFew+8, 0)
	a.Jcc(CondNE, g.exit)
	a.CmpMemImm8(R8, offSwNums, 0)
	a.Jcc(CondNE, g.exit)
	a.Jmp(none)
	a.Bind(numbers)
	a.MovQToX(0, R9)
	a.LoadSD(1, R8, offSwLo)
	a.SSEOp(UcomiSD, 0, 1)
	a.Jcc(CondB, none)
	a.LoadSD(3, R8, offSwHi)
	a.SSEOp(UcomiSD, 3, 0)
	a.Jcc(CondB, none)
	a.MovQToX(3, R9)
	a.SSEOp(SubSD, 3, 1)
	a.Cvttsd2si(RCX, 3)
	a.Cvtsi2sd(3, RCX, true)
	a.SSEOp(AddSD, 3, 1)
	a.SSEOp(UcomiSD, 3, 0)
	a.Jcc(CondNE, none)
	a.Jcc(CondP, none)
	a.CmpMem(RCX, R8, offSwDense+8, true)
	a.Jcc(CondAE, none)
	a.LeaIdx(RSI, RSI, RCX, 4, 0)
	a.LoadS32(RCX, RSI, 0)
	a.Op(Test, RCX, RCX, true)
	a.Jcc(CondS, none)
	a.Jmp(to)
	// A string, flat: a case of its length whose constant it is, or
	// whose text its is. The loop's state is in the scratch: sI the case
	// at hand, sEnd past the last, sV0 the case, sV1 the string.
	a.Bind(str)
	a.MovRR(RCX, R9)
	a.Op(Xor, RCX, R10, true)
	a.ShiftImm(Shr, RCX, 16, true)
	a.Jcc(CondNE, none)
	a.MovZX8(RCX, R9)
	a.OpImm(Cmp, RCX, int32(KindString), false)
	a.Jcc(CondE, isStr)
	// A boolean's case or null's (other); anything else has none.
	a.OpImm(Cmp, RCX, int32(KindNull), false)
	a.Jcc(CondE, null)
	a.OpImm(Cmp, RCX, int32(KindBool), false)
	a.Jcc(CondNE, none)
	a.LoadS32(RCX, R8, offSwOther+4)
	a.CmpMem(R9, RDI, ncTrue, true)
	a.Jcc(CondNE, other)
	a.LoadS32(RCX, R8, offSwOther)
	a.Jmp(other)
	a.Bind(null)
	a.LoadS32(RCX, R8, offSwOther+8)
	a.Bind(other)
	a.Op(Test, RCX, RCX, true)
	a.Jcc(CondS, none)
	a.Jmp(to)
	a.Bind(isStr)
	a.LoadIdx(RSI, R12, RDX, 1, 8)
	a.CmpMemImm8(RSI, offStrLeft, 0)
	a.Jcc(CondNE, g.exit)
	a.Store(RDI, scr(sV1), RSI)
	a.Load(RCX, RSI, offStrLen)
	a.Load(R9, R8, offSwByLen+8)
	a.OpImm(Sub, R9, 1, true)
	a.Op(Cmp, RCX, R9, true)
	a.Jcc(CondGE, none)
	a.Load(R9, R8, offSwByLen)
	a.LeaIdx(RDX, R9, RCX, 4, 0)
	a.LoadS32(RAX, RDX, 0)
	a.Store(RDI, scr(sI), RAX)
	a.LoadS32(RAX, RDX, 4)
	a.Store(RDI, scr(sEnd), RAX)
	a.Load(R9, R8, offSwFlat)
	a.Store(RDI, scr(sE), R9)
	a.Bind(loop)
	a.Load(RAX, RDI, scr(sI))
	a.CmpMem(RAX, RDI, scr(sEnd), true)
	a.Jcc(CondGE, none)
	a.MovImm(RCX, uint64(size("SwitchCase")))
	a.Imul(RCX, RAX)
	a.AddMem(RCX, RDI, scr(sE))
	a.Store(RDI, scr(sV0), RCX)
	// Its constant.
	a.Load(RSI, RDI, scr(sV1))
	a.Load(R8, RDI, ncCC)
	a.LoadU32(RDX, RCX, offSCK)
	a.CmpMem(RDX, R8, offCCConsts+8, true)
	a.Jcc(CondAE, text)
	a.ShiftImm(Shl, RDX, 4, true)
	a.AddMem(RDX, R8, offCCConsts)
	a.CmpMem(RSI, RDX, 8, true)
	a.Jcc(CondE, found)
	// Its text: the bytes, eight at a time, up to nativeFlatEqMax.
	a.Bind(text)
	a.Load(R9, RSI, offStrS+8)
	a.CmpMem(R9, RCX, offSCStr+8, true)
	a.Jcc(CondNE, next)
	a.OpImm(Cmp, R9, nativeFlatEqMax, true)
	a.Jcc(CondA, g.exit)
	a.Load(R8, RSI, offStrS)
	a.Load(RDX, RCX, offSCStr)
	a.Bind(words)
	a.OpImm(Cmp, R9, 8, true)
	a.Jcc(CondB, bytes)
	a.Load(RAX, R8, 0)
	a.CmpMem(RAX, RDX, 0, true)
	a.Jcc(CondNE, next)
	a.OpImm(Add, R8, 8, true)
	a.OpImm(Add, RDX, 8, true)
	a.OpImm(Sub, R9, 8, true)
	a.Jmp(words)
	a.Bind(bytes)
	a.Op(Test, R9, R9, true)
	a.Jcc(CondE, found)
	a.LoadU8(RAX, R8, 0)
	a.LoadU8(RSI, RDX, 0)
	a.Op(Cmp, RAX, RSI, false)
	a.Jcc(CondNE, next)
	a.OpImm(Add, R8, 1, true)
	a.OpImm(Add, RDX, 1, true)
	a.OpImm(Sub, R9, 1, true)
	a.Jmp(bytes)
	a.Bind(found)
	a.Load(RCX, RDI, scr(sV0))
	a.LoadU32(RCX, RCX, offSCTo)
	a.Jmp(to)
	a.Bind(next)
	a.Load(RAX, RDI, scr(sI))
	a.OpImm(Add, RAX, 1, true)
	a.Store(RDI, scr(sI), RAX)
	a.Jmp(loop)
	// The case's body.
	a.Bind(to)
	a.Load(RBX, RDI, ncCodeBase)
	a.LeaIdx(RBX, RBX, RCX, 8, 0)
	g.dispatch()
	a.Bind(none)
	g.next()
}
