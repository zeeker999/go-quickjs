package nativegen

import (
	"fmt"
	"strings"

	"github.com/go-quickjs/go-quickjs/internal/bytecode"
)

// handlersSource is the handlers' file for the block b: its code as bytes
// in one TEXT symbol, regNativeHandlers, and the native table,
// regNativeTable, a symbol of the handlers' addresses, every operation's
// that has none the exit stub's, which the linker resolves.
func handlersSource(b *block) []byte {
	var s strings.Builder
	s.WriteString("// Code generated by TestRegNativeGenerated (zzzyn_native_gen_amd64_test.go). DO NOT EDIT.\n\n#include \"textflag.h\"\n\n")
	fmt.Fprintf(&s, "// regNativeHandlers is the register interpreter's native handlers, %d\n", len(b.code))
	s.WriteString("// bytes of position-independent machine code made by nativeEmit: every\n// address it needs is in the context it is given in DI. Its handlers, in\n// order:\n//\n")
	for _, op := range b.order {
		fmt.Fprintf(&s, "//\t%5d  %s\n", b.at[op], op)
	}
	s.WriteString("TEXT ·regNativeHandlers(SB), NOSPLIT|NOFRAME, $0-0\n")
	for i := 0; i < len(b.code); i += 16 {
		var parts []string
		for _, c := range b.code[i:min(i+16, len(b.code))] {
			parts = append(parts, fmt.Sprintf("BYTE $0x%02x", c))
		}
		s.WriteString("\t" + strings.Join(parts, "; ") + "\n")
	}
	s.WriteString("\n// regNativeTable is the native table: each operation's handler's address,\n// the exit stub's where it has none.\n")
	for op := 0; op < 256; op++ {
		fmt.Fprintf(&s, "DATA ·regNativeTable+%d(SB)/8, $·regNativeHandlers+%d(SB)\n", 8*op, b.entry(bytecode.ROp(op)))
	}
	s.WriteString("GLOBL ·regNativeTable(SB), RODATA, $2048\n")
	return []byte(s.String())
}
