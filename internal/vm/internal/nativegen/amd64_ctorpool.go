package nativegen

import (
	"github.com/go-quickjs/go-quickjs/internal/bytecode"
	. "github.com/go-quickjs/go-quickjs/internal/jit/asm/amd64"
)

// ctorPool supplies a prepared object before the shared initializer.
func (g *nativeGen) ctorPool(start, call, after, entry Label) {
	a := g.a
	miss := a.NewLabel()
	a.Bind(start)
	g.reload()
	a.Load(R8, R13, int32(bytecode.RNewW)*8)
	a.LeaLabel(R9, entry)
	a.Op(Cmp, R8, R9, true)
	a.Jcc(CondNE, miss)
	a.Load(R9, RDI, ncRT)
	a.CmpMemImm8(R9, offRtInterrupt, 1)
	a.Jcc(CondLE, miss)
	a.Load(R8, R9, offRtFrameDepth)
	a.CmpMem(R8, R9, offRtMaxFrames, true)
	a.Jcc(CondGE, miss)
	a.Load(RAX, RBX, 0)
	g.newSite()
	a.Load(R8, RCX, offEThis+8)
	a.Op(Test, R8, R8, true)
	a.Jcc(CondE, miss)
	a.Load(R9, RCX, offECallee)
	a.Load(RDX, R9, off("Object.shape"))
	a.CmpMem(RDX, R8, off("regCtorCache.shape"), true)
	a.Jcc(CondNE, miss)
	a.Load(R8, R8, off("regCtorCache.pool"))
	a.Op(Test, R8, R8, true)
	a.Jcc(CondE, miss)
	a.CmpMemImm8(R8, off("nativeCtorPool.count"), 0)
	a.Jcc(CondE, miss)
	a.Store(RDI, scr(sV0), R8)
	a.Load(R9, R9, sizeObj+offExtData+8)
	a.Load(R9, R9, off("funcData.ctorRoot"))
	a.CmpMem(R9, R8, off("nativeCtorPool.root"), true)
	a.Jcc(CondNE, miss)
	a.LoadSD(0, RCX, offEThis)
	a.Cvttsd2si(RDX, 0)
	a.Load(R9, RCX, offECallee)
	a.Load(R9, R9, off("Object.valp"))
	a.ShiftImm(Shl, RDX, 4, true)
	a.Op(Add, RDX, R9, true)
	a.Load(R9, RDX, 0)
	a.CmpMem(R9, RDI, ncObjBits, true)
	a.Jcc(CondNE, miss)
	a.Load(RDX, RDX, 8)
	a.Load(R9, R8, off("nativeCtorPool.root"))
	a.CmpMem(RDX, R9, off("shape.proto"), true)
	a.Jcc(CondNE, miss)
	a.Load(RDX, R8, off("nativeCtorPool.count"))
	a.OpImm(Sub, RDX, 1, true)
	a.Store(R8, off("nativeCtorPool.count"), RDX)
	a.LeaIdx(R8, R8, RDX, 8, off("nativeCtorPool.objects"))
	a.Store(RDI, scr(sV1), R8)
	a.Load(RCX, R8, 0)
	a.Load(R9, RDI, ncObjBits)
	a.Store(RSI, 16, R9)
	a.Lea(RAX, RSI, 24)
	g.ptrStore()
	a.Load(RAX, RDI, scr(sV1))
	a.Op(Xor, RCX, RCX, true)
	g.ptrStore()
	a.StoreImm(RDI, scr(sV0), 0)
	a.MovImm(RAX, 3)
	a.Jmp(after)
	a.Bind(miss)
	g.reload()
	a.Load(RBX, RBX, 0)
	a.Load(RCX, RDI, ncIP)
	a.Load(RDX, RDI, ncCodeBase)
	a.Op(Sub, RCX, RDX, true)
	a.ShiftImm(Shr, RCX, 3, true)
	a.MovRR(RSI, RDI)
	a.MovRR(RAX, R12)
	a.Load(RDX, RDI, ncNewFn)
	a.Jmp(call)
}
