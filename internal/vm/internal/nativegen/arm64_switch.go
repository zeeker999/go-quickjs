package nativegen

import (
	. "github.com/go-quickjs/go-quickjs/internal/jit/asm/arm64"
)

// switchW is switch, as amd64's (amd64_switch.go).
func (g *armGen) switchW() {
	a := g.a
	str, to, none, loop, next := a.NewLabel(), a.NewLabel(), a.NewLabel(), a.NewLabel(), a.NewLabel()
	text, words, bytes, found := a.NewLabel(), a.NewLabel(), a.NewLabel(), a.NewLabel()
	isStr, null, other := a.NewLabel(), a.NewLabel(), a.NewLabel()
	// t := switches[BC].
	a.ShiftImm(Lsr, rC, rW, 32, true)
	a.Load(r8, rCtx, ncRC)
	g.cmpMem(rC, r8, offRCSwitches+8)
	a.BCond(HS, g.exit)
	a.Load(r8, r8, offRCSwitches)
	a.LoadIdx(r8, r8, rC, true)
	g.regA(rD)
	a.Load(r9, rD, 0)
	a.Cmp(r9, rTag, true)
	a.BCond(HS, str)
	// A number: dense[f-lo] where lo <= f <= hi and f-lo an integer.
	numbers := a.NewLabel()
	a.Load(rS, r8, offSwDense)
	a.Cbnz(rS, numbers, true)
	a.Load(rC, r8, offSwFew+8)
	a.Cbnz(rC, g.exit, true)
	a.Load(rC, r8, offSwNums)
	a.Cbnz(rC, g.exit, true)
	a.B(none)
	a.Bind(numbers)
	a.FMovToF(0, r9)
	a.LoadF(1, r8, offSwLo)
	a.LoadF(2, r8, offSwHi)
	a.FCmp(0, 1)
	a.BCond(LT, none)
	a.BCond(VS, none)
	a.FCmp(2, 0)
	a.BCond(LT, none)
	a.FArith(FSub, 3, 0, 1)
	a.Fcvtzs(rC, 3)
	a.Scvtf(3, rC, true)
	a.FArith(FAdd, 3, 3, 1)
	a.FCmp(3, 0)
	a.BCond(NE, none)
	g.cmpMem(rC, r8, offSwDense+8)
	a.BCond(HS, none)
	a.AddLsl(rS, rS, rC, 2)
	a.LoadS32(rC, rS, 0)
	a.CmpImm(rC, 0, true)
	a.BCond(LT, none)
	a.B(to)
	// A string, flat: a case of its length whose constant it is, or
	// whose text its is, as amd64's.
	a.Bind(str)
	a.Op(Eor, rC, r9, rTag, true)
	a.ShiftImm(Lsr, rC, rC, 16, true)
	a.Cbnz(rC, none, true)
	a.Ubfx(rC, r9, 0, 8)
	a.CmpImm(rC, int64(KindString), false)
	a.BCond(EQ, isStr)
	// A boolean's case or null's (other); anything else has none.
	a.CmpImm(rC, int64(KindNull), false)
	a.BCond(EQ, null)
	a.CmpImm(rC, int64(KindBool), false)
	a.BCond(NE, none)
	a.LoadS32(rC, r8, offSwOther+4)
	g.cmpMem(r9, rCtx, ncTrue)
	a.BCond(NE, other)
	a.LoadS32(rC, r8, offSwOther)
	a.B(other)
	a.Bind(null)
	a.LoadS32(rC, r8, offSwOther+8)
	a.Bind(other)
	a.CmpImm(rC, 0, true)
	a.BCond(LT, none)
	a.B(to)
	a.Bind(isStr)
	a.Load(rS, rD, 8)
	a.Load(rC, rS, offStrLeft)
	a.Cbnz(rC, g.exit, true)
	a.Store(rCtx, scr(sV1), rS)
	a.Load(rC, rS, offStrLen)
	a.Load(r9, r8, offSwByLen+8)
	a.AddImm(r9, r9, -1, true)
	a.Cmp(rC, r9, true)
	a.BCond(GE, none)
	a.Load(r9, r8, offSwByLen)
	a.AddLsl(rD, r9, rC, 2)
	a.LoadS32(rW, rD, 0)
	a.Store(rCtx, scr(sI), rW)
	a.LoadS32(rW, rD, 4)
	a.Store(rCtx, scr(sEnd), rW)
	a.Load(r9, r8, offSwFlat)
	a.Store(rCtx, scr(sE), r9)
	a.Bind(loop)
	a.Load(rW, rCtx, scr(sI))
	g.cmpMem(rW, rCtx, scr(sEnd))
	a.BCond(GE, none)
	a.MovImm(rC, uint64(size("SwitchCase")))
	a.Mul(rC, rC, rW)
	g.addMem(rC, rCtx, scr(sE))
	a.Store(rCtx, scr(sV0), rC)
	// Its constant.
	a.Load(rS, rCtx, scr(sV1))
	a.Load(r8, rCtx, ncCC)
	a.LoadU32(rD, rC, offSCK)
	g.cmpMem(rD, r8, offCCConsts+8)
	a.BCond(HS, text)
	a.ShiftImm(Lsl, rD, rD, 4, true)
	g.addMem(rD, r8, offCCConsts)
	g.cmpMem(rS, rD, 8)
	a.BCond(EQ, found)
	// Its text: the bytes, eight at a time, up to nativeFlatEqMax.
	a.Bind(text)
	a.Load(r9, rS, offStrS+8)
	g.cmpMem(r9, rC, offSCStr+8)
	a.BCond(NE, next)
	a.CmpImm(r9, nativeFlatEqMax, true)
	a.BCond(HI, g.exit)
	a.Load(r8, rS, offStrS)
	a.Load(rD, rC, offSCStr)
	a.Bind(words)
	a.CmpImm(r9, 8, true)
	a.BCond(LO, bytes)
	a.Load(rW, r8, 0)
	g.cmpMem(rW, rD, 0)
	a.BCond(NE, next)
	a.AddImm(r8, r8, 8, true)
	a.AddImm(rD, rD, 8, true)
	a.AddImm(r9, r9, -8, true)
	a.B(words)
	a.Bind(bytes)
	a.Cbz(r9, found, true)
	a.LoadU8(rW, r8, 0)
	a.LoadU8(rS, rD, 0)
	a.Cmp(rW, rS, false)
	a.BCond(NE, next)
	a.AddImm(r8, r8, 1, true)
	a.AddImm(rD, rD, 1, true)
	a.AddImm(r9, r9, -1, true)
	a.B(bytes)
	a.Bind(found)
	a.Load(rC, rCtx, scr(sV0))
	a.LoadU32(rC, rC, offSCTo)
	a.B(to)
	a.Bind(next)
	a.Load(rW, rCtx, scr(sI))
	a.AddImm(rW, rW, 1, true)
	a.Store(rCtx, scr(sI), rW)
	a.B(loop)
	// The case's body.
	a.Bind(to)
	a.Load(rIP, rCtx, ncCodeBase)
	a.AddLsl(rIP, rIP, rC, 3)
	g.dispatch()
	a.Bind(none)
	g.next()
}
