package nativegen

import (
	"github.com/go-quickjs/go-quickjs/internal/bytecode"
	. "github.com/go-quickjs/go-quickjs/internal/jit/asm/arm64"
)

// ctorPool supplies this without a call of Go, then rejoins the existing
// initializer path. A miss restores nativeNew's arguments before calling it.
func (g *armGen) ctorPool(start, call, after, entry Label) {
	a := g.a
	miss := a.NewLabel()
	a.Bind(start)
	// Feedback dispatch must enter the constructor's frame.
	a.Load(r8, rTab, int32(bytecode.RNewW)*8)
	a.Adr(r9, entry)
	a.Cmp(r8, r9, true)
	a.BCond(NE, miss)
	a.Load(r9, rCtx, ncRT)
	g.cmpMemImm(r9, offRtInterrupt, 1)
	a.BCond(LE, miss)
	a.Load(r8, r9, offRtFrameDepth)
	g.cmpMem(r8, r9, offRtMaxFrames)
	a.BCond(GE, miss)
	a.Load(rW, rIP, 0)
	g.newSite()
	a.Load(r8, rC, offEThis+8)
	a.Cbz(r8, miss, true)
	a.Load(r9, rC, offECallee)
	a.Load(rD, r9, off("Object.shape"))
	g.cmpMem(rD, r8, off("regCtorCache.shape"))
	a.BCond(NE, miss)
	a.Load(r8, r8, off("regCtorCache.pool"))
	a.Cbz(r8, miss, true)
	a.Load(rD, r8, off("nativeCtorPool.count"))
	a.Cbz(rD, miss, true)
	a.Store(rCtx, scr(sV0), r8)
	a.Load(r9, r9, sizeObj+offExtData+8)
	a.Load(r9, r9, off("funcData.ctorRoot"))
	g.cmpMem(r9, r8, off("nativeCtorPool.root"))
	a.BCond(NE, miss)
	a.LoadF(0, rC, offEThis)
	a.Fcvtzs(rD, 0)
	a.Load(r9, rC, offECallee)
	a.Load(r9, r9, off("Object.valp"))
	a.AddLsl(rD, r9, rD, 4)
	a.Load(r9, rD, 0)
	g.cmpMem(r9, rCtx, ncObjBits)
	a.BCond(NE, miss)
	a.Load(rD, rD, 8)
	a.Load(r9, r8, off("nativeCtorPool.root"))
	g.cmpMem(rD, r9, off("shape.proto"))
	a.BCond(NE, miss)
	a.Load(rD, r8, off("nativeCtorPool.count"))
	a.AddImm(rD, rD, -1, true)
	a.Store(r8, off("nativeCtorPool.count"), rD)
	a.AddImm(r8, r8, int64(off("nativeCtorPool.objects")), true)
	a.AddLsl(r8, r8, rD, 3)
	a.Store(rCtx, scr(sV1), r8)
	a.Load(rC, r8, 0)
	a.Load(r9, rCtx, ncObjBits)
	a.Store(rS, 16, r9)
	a.AddImm(rW, rS, 24, true)
	g.ptrStore()
	a.Load(rW, rCtx, scr(sV1))
	a.MovImm(rC, 0)
	g.ptrStore()
	g.storeImm(rCtx, scr(sV0), 0)
	a.MovImm(rW, 3)
	a.B(after)
	a.Bind(miss)
	g.reload()
	a.Load(rC, rIP, 0)
	a.Load(rD, rCtx, ncCodeBase)
	a.Op(Sub, rD, rIP, rD, true)
	a.ShiftImm(Lsr, rD, rD, 3, true)
	a.MovRR(rS, rCtx)
	a.MovRR(rW, rRegs)
	a.Load(rFn, rCtx, ncNewFn)
	a.B(call)
}
