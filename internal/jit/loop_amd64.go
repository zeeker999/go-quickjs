package jit

// The entry bridge supplies the state address in DI. Only CX and X0-X2 are
// clobbered; the stack, BP, and Go's R14 are untouched. Offsets are loopState's.
func loopInstructions() []byte {
	return []byte{
		0xf2, 0x0f, 0x10, 0x07, // movsd (di), x0
		0xf2, 0x0f, 0x10, 0x4f, 0x08, // movsd 8(di), x1
		0xf2, 0x0f, 0x10, 0x57, 0x10, // movsd 16(di), x2
		0x48, 0x8b, 0x4f, 0x18, // mov 24(di), cx
		0x48, 0x85, 0xc9, // test cx, cx
		0x74, 0x0d, // jz store
		0xf2, 0x0f, 0x58, 0xd0, // loop: addsd x0, x2
		0xf2, 0x0f, 0x58, 0xc1, // addsd x1, x0
		0x48, 0xff, 0xc9, // dec cx
		0x75, 0xf3, // jnz loop
		0xf2, 0x0f, 0x11, 0x07, // store: movsd x0, (di)
		0xf2, 0x0f, 0x11, 0x57, 0x10, // movsd x2, 16(di)
		0xc3, // ret
	}
}
